/**
 * 第 18 步 · 浏览器模块：一句话到底是**哪一种**指令。
 *
 * 这里全是**纯字符串**判定（不联网、不问模型），因为它决定「要不要发车」——
 * 猜错要么乱开网页，要么把用户的闲聊当成命令。
 *
 * 三种：
 *   detectOpenUrl        —— 开新页/换站（在 sites.ts）
 *   detectBrowseIntent   —— 在当前这张页面上干活
 *   detectStopIntent     —— 停手（第 18 步新增的唯一「让驾驶停下来」的口令）
 *
 * 另外两个确认词表（CONFIRM_ASK_RE / CONTINUE_*_RE）也放在这里，
 * 因为它们唯一的作用就是「要不要用工作台浏览器去执行」。
 */

import { looksLikeQuestion } from './sites';

/**
 * 第 16 步缺项修复：**已有网页**时，「普通浏览指令」判定。
 *
 * 背景：以前只有「明确开页指令」和「对确认提问回继续」才发车驾驶员循环，
 * 于是「在这个页面搜一下 AI」这种句子只会得到一句口头「稍等」，网页一动不动。
 *
 * 刻意保守：必须有明确的「对页面动手」动词才命中；纯闲聊（你好 / 谢谢 / 你是谁）一律不命中。
 * 没有活页时调用方也不会用它发车（不开第二张）。
 */
const BROWSE_ACT =
  /(搜一下|搜一搜|搜搜|搜索|搜个|搜\s|查一下|查一查|查查|查询|查找|读一下|读一读|读读|读页|读当前页|读这页|看一下这|看下这|看看这|看一下当前|往下滚|向下滚|往上滚|向上滚|滚一下|滚到底|滚动|翻页|下一页|上一页|刷新|重载|返回上一页|后退|点一下|点下|点击|点开|选中|勾选|填一下|帮我搜|帮我查|帮我点|帮我读|帮我翻|在这个页面|在当前页面|在当前这张|在这张页面|搜索框|输入框)/;

/** 明显是在提问、而不是下指令（比 detectOpenUrl 的判据更严：句中含疑问词也算） */
function looksLikeAsking(t: string): boolean {
  return (
    /^(怎么|如何|为什么|為什麽|怎样|怎樣|啥|什么|是不是|能不能|可以|要不要|该不该)/.test(t) ||
    /(是什么|什么意思|怎么办|怎么样|为什么|如何|吗？|吗\?|吗$|？|\?)/.test(t)
  );
}

/**
 * 从一句用户原话里解析出「要驾驶员在当前页面做的动作」。
 * 不是普通浏览指令就返回 null（调用方此时按纯聊天处理，不发车）。
 */
export function detectBrowseIntent(raw: string): string | null {
  const t = (raw ?? '').trim();
  if (!t || t.length > 120) return null;
  if (looksLikeQuestion(t) || looksLikeAsking(t)) return null;
  if (!BROWSE_ACT.test(t)) return null;
  return t;
}

/**
 * 第 18 步：「停」——**唯一**会让驾驶停下来的口令。
 *
 * 为什么需要它：第 17 步起「发一句话就把驾驶员暂停」被去掉了（闲聊不打断两路驾驶），
 * 于是必须有一个明确的口令负责停手，否则用户除了关页没有别的刹车。
 *
 * 刻意保守：整句就是停手口令（STOP_STRONG），或句子很短且含明确的停手说法（STOP_SOFT）；
 * 闲聊（你好 / 谢谢 / 你是谁 / 这个页面停不下来吗）都不会命中。
 */
const STOP_STRONG =
  /^(停|停下|停一下|停下来|停止|停止操作|停手|别动了|别动|不要动|不要继续|不要继续了|先停|先停下|暂停|暂停一下|取消|取消任务|算了|别弄了|stop|cancel)$/i;
const STOP_SOFT = /(停下来|别动了|不要动了|停止操作|别操作了|先别操作|不要继续了|停手|赶紧停|快停|别点了)/;

export function detectStopIntent(raw: string): boolean {
  const t = (raw ?? '').trim();
  if (!t || t.length > 40) return false;
  return STOP_STRONG.test(t) || STOP_SOFT.test(t);
}

/**
 * 第 16 步：确认是**例外**，不是默认。
 *
 * 模型只在「本会话第一次要用浏览器、且这句不是明确开页指令」时回那句固定话术；
 * 桌面靠下面这个正则识别「有一个待确认的浏览器任务」。
 * 用户回「继续 / 可以」= 同意 → **直接开页并起任务**，不再让他点按钮、也不再问一遍。
 * （和 server 端 promptPolicy.isContinueMarker 保持同一套词表。）
 */
export const CONFIRM_ASK_RE = /(确认后我开始操作|需要我用工作台浏览器|要我帮你(打开|操作|查|看)|要我打开|要不要我用浏览器)/;
export const CONTINUE_STRONG_RE =
  /^(继续|继续吧|可以继续|接着|接着来|接着做|按我上一条|按上面那条|按上一条|照上一条|就按这个|开始吧|开始|go\s*on|continue|ok\s*go|pls\s*continue)$/i;
/** 弱应答（可以 / 行 / 好 / 嗯）：**只有确实有待确认提问**时才算同意，平时不当确认用 */
export const CONTINUE_WEAK_RE = /^(可以|行|好的?|嗯|对|ok|okk?|好嘞|没问题)$/i;
